"""Project middleware for the AVDP GIS Portal."""

from urllib.parse import urlparse

from django.conf import settings


class PublicSchemeMiddleware:
    """Treat requests as HTTPS when the portal's public SITEURL is HTTPS.

    Django is only reachable through the nginx container on the internal
    Docker network. When HTTPS is terminated *in front of* nginx (GitHub
    Codespaces, a cloud load balancer, Cloudflare), nginx forwards
    ``X-Forwarded-Proto: http`` and Django would otherwise build ``http://``
    absolute URLs (for example the API index the map client reads its endpoint
    URLs from), which browsers block as mixed content on an HTTPS page.

    The GeoNode nginx image also replaces the browser's ``Origin`` header with
    ``http://<public host>``. That value is generated by nginx, not the
    browser, so it is mapped to the public HTTPS origin to stay consistent;
    Django's CSRF token check (cookie + form token) is unaffected.
    """

    def __init__(self, get_response):
        self.get_response = get_response
        public = urlparse(settings.SITEURL)
        self.https = public.scheme == "https"
        self.nginx_origin = f"http://{public.netloc}"
        self.public_origin = f"https://{public.netloc}"

    def __call__(self, request):
        if self.https:
            # request.META is the WSGI environ; Django derives request.scheme from it.
            request.META["wsgi.url_scheme"] = "https"
            if request.META.get("HTTP_ORIGIN") == self.nginx_origin:
                request.META["HTTP_ORIGIN"] = self.public_origin
        return self.get_response(request)
