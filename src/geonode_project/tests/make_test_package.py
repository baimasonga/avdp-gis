"""Generate a TEST FIXTURE shaped like the AVDP synthetic sample package.

This is NOT the AVDP_Synthetic_GIS_Sample_Package.zip. It exists only so the
validation and import tooling can be exercised end-to-end when the real
package is not available. Every layer, attribute and file name is marked
"TEST FIXTURE" and coordinates are random points inside an inland box.

Usage (inside the django container):
    python -m geonode_project.tests.make_test_package /tmp/avdp_test_fixture.zip
"""

import csv
import json
import os
import random
import sys
import tempfile
import zipfile

from osgeo import ogr, osr

from geonode_project.avdp.demo_package import LAYERS

FIXTURE_LABEL = "TEST FIXTURE - generated by make_test_package.py - not AVDP data"
BOX = (-12.4, 7.6, -10.9, 9.4)  # inland lon/lat box used for random geometry
DISTRICTS = ["District A", "District B", "District C", "District D"]
VALUES = {
    "farm_plots": ("crop", ["Rice", "Cassava", "Maize", "Groundnut"]),
    "farmer_groups": ("group_type", ["Cooperative", "Association", "Women's group"]),
    "feeder_roads": ("condition", ["Good", "Fair", "Poor"]),
    "water_points": ("status", ["Functional", "Needs repair", "Not functional"]),
    "grain_stores": ("status", ["Operational", "Under construction"]),
    "distribution_sites": ("input_type", ["Seed", "Fertiliser", "Tools"]),
    "demonstration_plots": ("technology", ["Improved seed", "Intercropping", "Water harvesting"]),
}


def _geometry(rng, family):
    x = rng.uniform(BOX[0], BOX[2])
    y = rng.uniform(BOX[1], BOX[3])
    if family == "point":
        g = ogr.Geometry(ogr.wkbPoint)
        g.AddPoint_2D(x, y)
    elif family == "line":
        g = ogr.Geometry(ogr.wkbLineString)
        for _ in range(4):
            g.AddPoint_2D(x, y)
            x += rng.uniform(0.01, 0.04)
            y += rng.uniform(-0.02, 0.02)
    else:
        d = rng.uniform(0.002, 0.006)
        ring = ogr.Geometry(ogr.wkbLinearRing)
        for px, py in ((x, y), (x + d, y), (x + d, y + d), (x, y + d), (x, y)):
            ring.AddPoint_2D(px, py)
        g = ogr.Geometry(ogr.wkbPolygon)
        g.AddGeometry(ring)
    return g


def build(zip_path, seed=42):
    rng = random.Random(seed)
    srs = osr.SpatialReference()
    srs.ImportFromEPSG(4326)
    with tempfile.TemporaryDirectory() as tmp:
        root = os.path.join(tmp, "AVDP_test_fixture")
        for sub in ("shapefiles", "geojson", "attributes"):
            os.makedirs(os.path.join(root, sub))
        for spec in LAYERS:
            family = spec.geometry[-1] if spec.key == "demonstration_plots" else spec.geometry[0]
            field_name, values = VALUES[spec.key]
            rows = []
            for i in range(spec.expected_count):
                rows.append(
                    {
                        "site_id": f"{spec.key[:3].upper()}-{i + 1:03d}",
                        "name": f"Test {spec.title.lower()} {i + 1}",
                        field_name: rng.choice(values),
                        "dist_label": rng.choice(DISTRICTS),
                        "benefic": rng.randint(5, 120),
                        "synthetic": "yes",
                        "geom": _geometry(rng, family),
                    }
                )
            for driver, folder, ext in (("GeoJSON", "geojson", "geojson"), ("ESRI Shapefile", "shapefiles", "shp")):
                path = os.path.join(root, folder, f"{spec.key}.{ext}")
                ds = ogr.GetDriverByName(driver).CreateDataSource(path)
                gtype = {"point": ogr.wkbPoint, "line": ogr.wkbLineString, "polygon": ogr.wkbPolygon}[family]
                layer = ds.CreateLayer(spec.key, srs, gtype)
                for name, ftype in (
                    ("site_id", ogr.OFTString),
                    ("name", ogr.OFTString),
                    (field_name, ogr.OFTString),
                    ("dist_label", ogr.OFTString),
                    ("benefic", ogr.OFTInteger),
                    ("synthetic", ogr.OFTString),
                ):
                    layer.CreateField(ogr.FieldDefn(name, ftype))
                for row in rows:
                    feat = ogr.Feature(layer.GetLayerDefn())
                    for k, v in row.items():
                        if k != "geom":
                            feat.SetField(k, v)
                    feat.SetGeometry(row["geom"])
                    layer.CreateFeature(feat)
                ds = None
            with open(os.path.join(root, "attributes", f"{spec.key}.csv"), "w", newline="") as handle:
                writer = csv.writer(handle)
                writer.writerow(["site_id", "name", field_name, "dist_label", "benefic", "synthetic"])
                for row in rows:
                    writer.writerow(
                        [
                            row["site_id"],
                            row["name"],
                            row[field_name],
                            row["dist_label"],
                            row["benefic"],
                            row["synthetic"],
                        ]
                    )
        with open(os.path.join(root, "README.txt"), "w") as handle:
            handle.write(FIXTURE_LABEL + "\n")
        with open(os.path.join(root, "fixture.json"), "w") as handle:
            json.dump({"label": FIXTURE_LABEL, "seed": seed}, handle)
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as archive:
            for dirpath, _, filenames in os.walk(root):
                for filename in filenames:
                    full = os.path.join(dirpath, filename)
                    archive.write(full, os.path.relpath(full, tmp))
    return zip_path


if __name__ == "__main__":
    print(build(sys.argv[1] if len(sys.argv) > 1 else "/tmp/avdp_test_fixture.zip"))
